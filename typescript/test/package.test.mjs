import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { test } from 'node:test';

const root = resolve(import.meta.dirname, '../..');
test('packed exports preserve constants, units and tiers', () => {
  const temp = mkdtempSync(resolve(tmpdir(), 'qyl-semconv-'));
  try {
    const output = JSON.parse(execFileSync('npm', ['pack', './typescript', '--json', '--pack-destination', temp], {cwd:root,encoding:'utf8'}));
    const packages = Array.isArray(output) ? output : Object.values(output);
    assert.equal(packages.length, 1);
    const [packed] = packages;
    assert.equal(packed.name, '@ancplua/qyl-semantic-conventions');
    assert.equal(packed.version, JSON.parse(readFileSync(resolve(root, 'typescript/package.json'))).version);
    assert.equal(typeof packed.filename, 'string');
    execFileSync('npm', ['install', '--prefix', temp, '--ignore-scripts', '--no-audit', '--no-fund', resolve(temp, packed.filename)], {encoding:'utf8'});
    const check = `
import assert from 'node:assert/strict';
import * as stable from '@ancplua/qyl-semantic-conventions';
import * as all from '@ancplua/qyl-semantic-conventions/incubating';
import { findAttribute, findMetric } from '@ancplua/qyl-semantic-conventions/catalog';
import { getCapturedFieldPersistence } from '@ancplua/qyl-semantic-conventions/policy';
assert.equal(getCapturedFieldPersistence('HTTP.REQUEST.HEADER.AUTHORIZATION'), true);
assert.equal(getCapturedFieldPersistence('rpc.response.metadata.trace-bin'), true);
assert.equal(getCapturedFieldPersistence('http.request.header'), false);
assert.equal(getCapturedFieldPersistence('rpc.request.metadata.x+feature'), false);
assert.equal(getCapturedFieldPersistence('http.request.headers.authorization'), undefined);
assert.equal(stable.ATTR_SERVICE_NAME, 'service.name');
assert.equal(stable.NETWORK_TRANSPORT_VALUE_TCP, 'tcp');
assert.equal(all.ATTR_MCP_METHOD_NAME, 'mcp.method.name');
assert.equal(all.CLOUD_PLATFORM_VALUE_AZURE_VM, 'azure.vm');
assert.ok(!Object.values(all).includes('azure_vm'));
assert.equal(all.GEN_AI_OPERATION_NAME_VALUE_EXECUTE_TOOL, 'execute_tool');
assert.equal(all.ATTR_QYL_MCP_EXECUTION_ID, 'qyl.mcp.execution.id');
assert.equal(all.EVENT_QYL_MCP_OPERATION, 'qyl.mcp.operation');
assert.equal(all.METRIC_MCP_SERVER_OPERATION_DURATION_UNIT, 's');
assert.equal(all.METRIC_MCP_SERVER_OPERATION_DURATION_DEFINITION.instrument, 'histogram');
assert.equal(all.METRIC_QYL_COLLECTOR_ATTRIBUTES_SANITIZATION_FAILED, 'qyl.collector.attributes.sanitization.failed');
assert.equal(all.METRIC_QYL_COLLECTOR_ATTRIBUTES_SANITIZATION_FAILED_UNIT, '{attribute}');
assert.equal(all.METRIC_QYL_COLLECTOR_ATTRIBUTES_SANITIZATION_FAILED_DEFINITION.instrument, 'counter');
assert.equal(all.QYL_ATTRIBUTE_KEY_VALUE_EXCEPTION_MESSAGE, 'exception.message');
assert.equal(all.QYL_ATTRIBUTE_KEY_VALUE_EXCEPTION_STACKTRACE, 'exception.stacktrace');
assert.equal(stable.ATTR_MCP_METHOD_NAME, undefined);
assert.equal(findAttribute('http.response.status_code').valueKind, 'Integer');
const header = findAttribute('http.request.header.content_type');
assert.equal(header.name, 'http.request.header');
assert.equal(header.valueKind, 'StringArray');
assert.equal(header.isTemplate, true);
assert.equal(findAttribute('http.request.header.'), undefined);
assert.equal(findAttribute('http.request.header'), undefined);
assert.equal(findAttribute('Service.Name'), undefined);
assert.equal(findAttribute('shop.order.id'), undefined);
assert.equal(findAttribute('db.system').deprecated.renamed_to, 'db.system.name');
assert.equal(findAttribute('exception.escaped').deprecated.reason, 'obsoleted');
assert.equal(findAttribute('exception.escaped').deprecated.renamed_to, undefined);
assert.equal(findAttribute('code.function').deprecated.note, ${JSON.stringify('Value should be included in `code.function.name` which is expected to be a fully-qualified name.\n')});
assert.equal(findMetric('http.server.request.duration').unit, 's');
assert.equal(findMetric('http.server.request.duration').instrument, 'histogram');
assert.equal(findMetric('system.cpu.time').stability, 'development');
assert.equal(findMetric('cpu.time').deprecated.renamed_to, 'system.cpu.time');
assert.equal(findMetric('shop.order.total'), undefined);
assert.equal(findMetric('HTTP.server.request.duration'), undefined);
assert.ok(Object.isFrozen(header));
assert.ok(Object.isFrozen(findAttribute('db.system').deprecated));
assert.throws(() => { header.valueKind = 'Integer'; }, TypeError);
for (const [key,value] of Object.entries(stable)) assert.deepEqual(all[key], value);
`;
    execFileSync('node', ['--input-type=module', '-e', check], {cwd:temp,encoding:'utf8'});
    const pkg = JSON.parse(readFileSync(resolve(temp, 'node_modules/@ancplua/qyl-semantic-conventions/package.json')));
    assert.equal(pkg.sideEffects, false);
    assert.equal(pkg.dependencies, undefined);
    for (const name of ['.', './incubating']) assert.ok(readFileSync(resolve(temp, 'node_modules/@ancplua/qyl-semantic-conventions', pkg.exports[name].types), 'utf8').includes('export declare const ATTR_'));
    assert.ok(readFileSync(resolve(temp, 'node_modules/@ancplua/qyl-semantic-conventions', pkg.exports['./catalog'].types), 'utf8').includes('findAttribute(key: string): RegistryAttributeInfo | undefined'));
    assert.ok(readFileSync(resolve(temp, 'node_modules/@ancplua/qyl-semantic-conventions', pkg.exports['./policy'].types), 'utf8').includes('getCapturedFieldPersistence(key: string): boolean | undefined'));
  } finally { rmSync(temp, {recursive:true,force:true}); }
});
