#!/usr/bin/env python3
"""Generate span routing from resolved contracts and their registry-owned naming rules."""
import json
from pathlib import Path
import re
import sys


def name_pattern(template, attributes, substitutions):
    parts, anchored, position = [], False, 0
    for match in re.finditer(r"\{([^{}]+)\}", template):
        literal = template[position:match.start()]
        anchored |= bool(literal.strip())
        parts.append(re.escape(literal))
        key = match[1]
        attribute_type = attributes.get(key, {}).get("type", {})
        members = attribute_type.get("members", []) if isinstance(attribute_type, dict) else []
        values = {str(substitutions.get(key, {}).get(str(m["value"]), m["value"])) for m in members}
        if values:
            parts.append("(?:" + "|".join(re.escape(v) for v in sorted(values)) + ")")
            anchored = True
        else:
            parts.append(".+")
        position = match.end()
    literal = template[position:]
    anchored |= bool(literal.strip())
    parts.append(re.escape(literal))
    # A free-form query or model name cannot identify a signal. Keep its explicit type route.
    return "^" + "".join(parts) + "$" if anchored else None


def matchers(registry, policy):
    result = []
    for span in sorted(registry["registry"]["spans"], key=lambda s: s["type"]):
        signal, kind = span["type"], span["kind"]
        rule = policy["spans"].get(signal, {})
        attributes = {a["key"]: a for a in span.get("attributes", [])}
        patterns = {p for template in rule.get("templates", [])
                    if (p := name_pattern(template, attributes, rule.get("substitutions", {})))}
        # The type route also permits explicitly typed telemetry with dynamic or ambiguous names.
        names = ["name == " + json.dumps(signal)]
        names += ["name.matches(" + json.dumps(p) + ")" for p in sorted(patterns)]
        when = "kind == " + json.dumps(kind) + " && (" + " || ".join(names) + ")"
        result.append({"id": "span." + signal, "sample_type": "span", "when": when, "signal": signal})
    return result


def render(rows):
    lines = [
        "# Generated by scripts/generate-live-check.py from Weaver and registry/qyl/policy.yaml.",
        "# Edit the naming contract, then run scripts/generate.sh.",
        "[registry]", "v2 = true", "",
        '["live-check"]', "search_all_attributes = true", "",
        '# Replaced by the registry-driven qyl advice policies.',
        '[["live-check".finding_filters]]',
        'exclude = ["deprecated", "type_mismatch", "undefined_enum_variant"]',
    ]
    for row in rows:
        lines += ["", '[["live-check".matchers]]']
        lines += [key + " = " + json.dumps(value) for key, value in row.items()]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    registry = json.loads(Path(sys.argv[1]).read_text())
    policy = json.loads(Path(sys.argv[2]).read_text())["params"]["policy"]
    rows = matchers(registry, policy)
    Path(sys.argv[3]).write_text(render(rows))
    print(f"Generated {len(rows)} span matchers from the resolved registry and naming contracts.")
