#!/usr/bin/env python3
"""Generate tree-shakable JavaScript, literal declarations and TS from Weaver v2.

The dependency fallback and stable/deprecated tiers match csharp/weaver.yaml.
No SDK or hand-maintained convention tables participate in generation.
"""
import hashlib
import json
import re
import sys
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent

def symbol(value):
    return re.sub(r'[^A-Z0-9]+', '_', value.upper()).strip('_')

def attribute_symbols(attributes):
    """Keep canonical dotted names; expose a colliding underscore spelling as NATIVE."""
    groups = {}
    for attribute in attributes:
        groups.setdefault(symbol(attribute['key']), []).append(attribute['key'])
    result = {}
    occupied = set()
    for name, keys in sorted(groups.items()):
        most_segments = max(key.count('.') for key in keys)
        dotted = [key for key in keys if key.count('.') == most_segments]
        for key in keys:
            projected = name
            if len(keys) > 1:
                if (len(keys) != 2 or len(dotted) != 1
                        or any(re.sub(r'[_-]', '.', item) != re.sub(r'[_-]', '.', dotted[0]) for item in keys)):
                    raise ValueError(f'attribute identifier collision: {keys}')
                if key != dotted[0]:
                    projected += '_NATIVE'
            if projected in occupied:
                raise ValueError(f'attribute identifier collision: {projected}')
            occupied.add(projected)
            result[key] = projected
    return result

def semantic_snapshot(value):
    """Ignore filesystem provenance paths; keep source URLs and all registry semantics."""
    if isinstance(value, dict):
        result = {}
        for key, item in value.items():
            if key == 'provenance':
                item = {field: data for field, data in item.items()
                        if field != 'path' or data.startswith(('https://', 'http://'))}
            result[key] = semantic_snapshot(item)
        return result
    if isinstance(value, list):
        return [semantic_snapshot(item) for item in value]
    return value

def generate_catalog(catalog, out, digest):
    """Use the same normalized Weaver facts as C# and the private analyzer catalog."""
    header = f'// Generated by scripts/generate.sh from Weaver v2; do not edit.\n// Registry snapshot: {digest}\n// SPDX-License-Identifier: Apache-2.0\n'
    kinds = ' | '.join(json.dumps(kind) for kind in ['Unknown', 'String', 'Integer', 'Double', 'Boolean', 'StringArray', 'IntegerArray', 'DoubleArray', 'BooleanArray', 'Any'])
    interfaces = (
        '/** Registry membership does not prohibit custom OpenTelemetry names or assign scope ownership. */\n'
        f'export type RegistryAttributeValueKind = {kinds};\n'
        'export interface RegistryDeprecation { readonly reason: string; readonly renamed_to?: string; readonly note?: string; }\n'
        'export interface RegistryAttributeInfo { readonly name: string; readonly valueKind: RegistryAttributeValueKind; readonly isTemplate: boolean; readonly stability: string; readonly deprecated: RegistryDeprecation | null; }\n'
        'export interface RegistryMetricInfo { readonly name: string; readonly instrument: string; readonly unit: string | null; readonly stability: string; readonly deprecated: RegistryDeprecation | null; }\n'
    )
    def literal(row):
        fields = []
        for key, value in row.items():
            encoded = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
            if key == 'deprecated' and value is not None:
                encoded = f'Object.freeze({encoded})'
            fields.append(f'{json.dumps(key)}:{encoded}')
        return 'Object.freeze({' + ','.join(fields) + '})'
    attributes = [dict(name=a['key'], valueKind=a['kind'], isTemplate=a['template'],
                       stability=a.get('stability') or 'development', deprecated=a.get('deprecated'))
                  for a in catalog['attributes']]
    metrics = [dict(name=m['name'], instrument=m['instrument'], unit=m.get('unit'),
                    stability=m.get('stability') or 'development', deprecated=m.get('deprecated'))
               for m in catalog['metrics']]
    for typed, directory, suffix in [(False, 'dist', 'js'), (True, 'src', 'ts')]:
        source = [header, interfaces if typed else '']
        for name, rows, shape in [('attributeRows', attributes, 'RegistryAttributeInfo'), ('metricRows', metrics, 'RegistryMetricInfo')]:
            source.append(f'const {name}' + (f': ReadonlyArray<{shape}>' if typed else '') + ' = [\n')
            source.extend('  ' + literal(row) + ',\n' for row in rows)
            source.append('];\n')
        source.append('const attributes = new Map(attributeRows.filter(row => !row.isTemplate).map(row => [row.name, row]));\n')
        source.append('const templates = attributeRows.filter(row => row.isTemplate).sort((a, b) => b.name.length - a.name.length);\n')
        source.append('const metrics = new Map(metricRows.map(row => [row.name, row]));\n')
        argument = 'key: string' if typed else 'key'
        result = ': RegistryAttributeInfo | undefined' if typed else ''
        source.append('/** Exact keys and nonempty template expansions; requirements stay with their signal definitions. */\n')
        source.append(f'export function findAttribute({argument}){result} {{\n'
                      '  return attributes.get(key) ?? templates.find(row => key.length > row.name.length + 1 && key.startsWith(row.name + "."));\n}\n')
        argument = 'name: string' if typed else 'name'
        result = ': RegistryMetricInfo | undefined' if typed else ''
        source.append('/** An unknown custom metric is not an OpenTelemetry error. */\n')
        source.append(f'export function findMetric({argument}){result} {{ return metrics.get(name); }}\n')
        (out / directory / f'catalog.{suffix}').write_text(''.join(source))
    (out / 'dist/catalog.d.ts').write_text(header + interfaces +
        'export declare function findAttribute(key: string): RegistryAttributeInfo | undefined;\n'
        'export declare function findMetric(name: string): RegistryMetricInfo | undefined;\n')

def generate_policy(policy, out, digest):
    """Share the captured-field definition passed to the C# Weaver templates."""
    header = f'// Generated by scripts/generate.sh from registry/qyl/policy.yaml; do not edit.\n// Registry snapshot: {digest}\n// SPDX-License-Identifier: Apache-2.0\n'
    captured = policy['captured_fields']
    for typed, directory, suffix in [(False, 'dist', 'js'), (True, 'src', 'ts')]:
        source = [header]
        for protocol in ('http', 'rpc'):
            source.append(f'const {protocol}Roots = ' + json.dumps(captured[f'{protocol}_roots']) + (' as const' if typed else '') + ';\n')
            source.append(f'const {protocol}NameCharacters = ' + json.dumps(captured[f'{protocol}_name_characters']) + ';\n')
        argument = 'key: string' if typed else 'key'
        result = ': boolean | undefined' if typed else ''
        source.append(
            '/** True for valid captured names, false for bare/invalid captured families, undefined for unrelated keys.\n'
            ' * Classifies names only; callers own capture selection and value shape. */\n'
            f'export function getCapturedFieldPersistence({argument}){result} {{\n'
            '  // Fold ASCII only: Unicode case conversion must not admit non-protocol characters.\n'
            '  const comparison = key.replace(/[A-Z]/g, letter => letter.toLowerCase());\n'
            '  for (const [roots, allowed] of [[httpRoots, httpNameCharacters], [rpcRoots, rpcNameCharacters]]' + (' as const' if typed else '') + ') {\n'
            '    for (const root of roots) {\n'
            '      if (comparison === root) return false;\n'
            '      if (!comparison.startsWith(root + ".")) continue;\n'
            '      const name = comparison.slice(root.length + 1);\n'
            '      if (name.length === 0) return false;\n'
            '      for (const character of name) {\n'
            '        if (!allowed.includes(character)) return false;\n'
            '      }\n'
            '      return true;\n'
            '    }\n'
            '  }\n'
            '  return undefined;\n'
            '}\n')
        (out / directory / f'policy.{suffix}').write_text(''.join(source))
    (out / 'dist/policy.d.ts').write_text(header +
        '/** True for valid captured names, false for bare/invalid captured families, undefined for unrelated keys.\n'
        ' * Classifies names only; callers own capture selection and value shape. */\n'
        'export declare function getCapturedFieldPersistence(key: string): boolean | undefined;\n')

def generate(snapshot, catalog, policy):
    version = ET.parse(ROOT / 'Directory.Build.props').getroot().findtext('.//VersionPrefix')
    if snapshot['schema_url'] != f'https://qyl.at/schemas/{version}':
        raise ValueError('schema_url differs from VersionPrefix')
    def rows(kind, key):
        result = {}
        for dependency in snapshot['dependencies'].values():
            for row in dependency['registry'].get(kind, []):
                result.setdefault(row[key], row)
        for row in snapshot['registry'].get(kind, []):
            result[row[key]] = row
        return sorted(result.values(), key=lambda r: r[key])
    attributes, metrics, events = rows('attributes', 'key'), rows('metrics', 'name'), rows('events', 'name')
    digest = hashlib.sha256(json.dumps(semantic_snapshot(snapshot), sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    (ROOT / 'src/Qyl.Telemetry.SemanticConventions/Generated/RegistrySnapshot.g.cs').write_text(
        '// <auto-generated/>\n// Generated from the same resolved Weaver registry as TypeScript.\n'
        '// SPDX-License-Identifier: Apache-2.0\n\nnamespace Qyl.Telemetry.SemanticConventions;\n\n'
        '/// <summary>Fingerprint of the resolved registry, excluding source-location metadata.</summary>\n'
        'public static class RegistrySnapshot\n{\n'
        '    /// <summary>SHA-256 shared by the generated C# and TypeScript bindings.</summary>\n'
        f'    public const string Sha256 = "{digest}";\n}}\n')
    out = ROOT / 'typescript'
    (out / 'src').mkdir(parents=True, exist_ok=True)
    (out / 'dist').mkdir(parents=True, exist_ok=True)
    for tier, name in [('stable', 'index'), ('incubating', 'incubating')]:
        values = {}
        def add(key, value):
            if key in values and values[key] != value:
                raise ValueError(f'identifier collision: {key}')
            values[key] = value
        def include(row):
            return not row.get('annotations', {}).get('code_generation', {}).get('exclude', False) and (tier == 'incubating' or row.get('stability') == 'stable' or row.get('deprecated') is not None)
        add('SCHEMA_URL', snapshot['schema_url'])
        add('REGISTRY_SNAPSHOT_SHA256', digest)
        names = attribute_symbols([a for a in attributes if include(a)])
        for a in attributes:
            if not include(a):
                continue
            add('ATTR_' + names[a['key']], a['key'])
            if isinstance(a['type'], dict):
                for member in a['type'].get('members', []):
                    if not member.get('annotations', {}).get('code_generation', {}).get('exclude', False) and (tier == 'incubating' or member.get('stability', a.get('stability')) == 'stable' or member.get('deprecated')):
                        add(symbol(a['key']) + '_VALUE_' + symbol(member['id']), member['value'])
        for m in metrics:
            if include(m):
                key = 'METRIC_' + symbol(m['name'])
                add(key, m['name'])
                add(key + '_UNIT', m.get('unit', ''))
                add(key + '_DEFINITION', {'name': m['name'], 'unit': m.get('unit', ''), 'instrument': m['instrument'], 'stability': m.get('stability', 'development')})
        for e in events:
            if include(e):
                add('EVENT_' + symbol(e['name']), e['name'])
        header = f'// Generated by scripts/generate.sh from Weaver v2; do not edit.\n// Registry snapshot: {digest}\n// SPDX-License-Identifier: Apache-2.0\n'
        js, ts, declarations = [header], [header], [header]
        for key, value in sorted(values.items()):
            literal = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
            js.append(f'export const {key} = {literal};\n')
            ts.append(f'export const {key} = {literal} as const;\n')
            typ = ('{ readonly name: ' + json.dumps(value['name']) + '; readonly unit: ' + json.dumps(value['unit']) + '; readonly instrument: ' + json.dumps(value['instrument']) + '; readonly stability: ' + json.dumps(value['stability']) + '; }') if isinstance(value, dict) else literal
            declarations.append(f'export declare const {key}: {typ};\n')
        (out / 'src' / f'{name}.ts').write_text(''.join(ts))
        (out / 'dist' / f'{name}.js').write_text(''.join(js))
        (out / 'dist' / f'{name}.d.ts').write_text(''.join(declarations))
    generate_catalog(catalog, out, digest)
    generate_policy(policy, out, digest)
    package = {'name': '@ancplua/qyl-semantic-conventions', 'version': version, 'description': 'qyl semantic convention constants generated from the shared OpenTelemetry registry', 'type': 'module', 'sideEffects': False, 'license': 'Apache-2.0', 'repository': {'type':'git', 'url':'git+https://github.com/ANcpLua/Qyl.Telemetry.SemanticConventions.git', 'directory':'typescript'}, 'exports': {'.':{'types':'./dist/index.d.ts','import':'./dist/index.js'}, './incubating':{'types':'./dist/incubating.d.ts','import':'./dist/incubating.js'}, './catalog':{'types':'./dist/catalog.d.ts','import':'./dist/catalog.js'}}, 'files':['dist','src','README.md','LICENSE'], 'publishConfig':{'access':'public'}, 'scripts':{'test':'node --test test/*.test.mjs'}}
    package['exports']['./policy'] = {'types': './dist/policy.d.ts', 'import': './dist/policy.js'}
    (out / 'package.json').write_text(json.dumps(package, indent=2) + '\n')
    (out / 'LICENSE').write_text((ROOT / 'LICENSE').read_text())
    print(f'Generated TypeScript {version}: {len(attributes)} attributes, {len(metrics)} metrics, {len(events)} events; snapshot {digest}')

if __name__ == '__main__':
    generate(json.loads(Path(sys.argv[1]).read_text()), json.loads((ROOT / '.build/registry-catalog.json').read_text()), json.loads(sys.argv[2]))
