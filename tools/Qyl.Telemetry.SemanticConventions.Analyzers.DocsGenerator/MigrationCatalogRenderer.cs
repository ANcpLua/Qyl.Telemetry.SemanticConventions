using System.Collections.Immutable;
using System.Text;
using SemconvMigrationCatalog = analyzers::Qyl.Telemetry.SemanticConventions.Analyzers.SemconvMigrationCatalog;
using SemconvMigrationCatalogEntry = analyzers::Qyl.Telemetry.SemanticConventions.Analyzers.SemconvMigrationCatalogEntry;
using SemconvMigrationItemKind = analyzers::Qyl.Telemetry.SemanticConventions.Analyzers.SemconvMigrationItemKind;
